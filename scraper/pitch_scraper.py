def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculate great-circle distance between two GPS coordinates in kilometers."""
    r = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlam = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2.0) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlam / 2.0) ** 2
    return 2.0 * r * math.asin(math.sqrt(a))


def query_photon_pitches(query: str, limit: int = 40) -> List[Dict[str, Any]]:
    """Query Photon API for pitch features within the Munich and Landkreis bounding box."""
    bbox_str = f"{BBOX['west']},{BBOX['south']},{BBOX['east']},{BBOX['north']}"
    url = f"{PHOTON_API_URL}?q={urllib.parse.quote(query)}&bbox={bbox_str}&limit={limit}"
    req = urllib.request.Request(url, headers=HTTP_HEADERS)
    try:
        with urllib.request.urlopen(req, timeout=5) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return data.get("features", [])
    except Exception:
        return []


def collect_live_pitches(verbose: bool = True) -> List[Dict[str, Any]]:
    """Query Photon to discover additional Bolzplätze and sports facilities if available."""
    queries = ["Bolzplatz München", "Bolzplatz Landkreis München", "Bezirkssportanlage"]
    live_features = []

    if verbose:
        print("[Pitch Scraper] Checking live geodata sources...")

    for q in queries:
        feats = query_photon_pitches(q, limit=30)
        live_features.extend(feats)
        time.sleep(0.1)

    converted = []
    for f in live_features:
        coords = f.get("geometry", {}).get("coordinates", [0, 0])
        lng, lat = coords[0], coords[1]
        if lat < BBOX["south"] or lat > BBOX["north"] or lng < BBOX["west"] or lng > BBOX["east"]:
            continue

        p = f.get("properties", {})
        name = p.get("name") or "Städtischer Bolzplatz"
        street = p.get("street", "")
        district = p.get("district") or p.get("city") or "München"
        postcode = p.get("postcode", "")

        addr = f"{street}, {postcode} {district}".strip(", ") if street else f"{district}"

        name_lower = name.lower()
        if "kunstrasen" in name_lower:
            surface = "Kunstrasen"
        elif "hartplatz" in name_lower or "tenne" in name_lower or "schlacke" in name_lower:
            surface = "Hartplatz"
        elif "asphalt" in name_lower or "beton" in name_lower:
            surface = "Asphalt"
        else:
            surface = "Rasenplatz"

        cage = any(w in name_lower for w in ["käfig", "cage", "court", "bande", "gitter"])
        is_official = "bezirkssportanlage" in name_lower or "sportpark" in name_lower

        converted.append({
            "name": name,
            "address": addr,
            "district": district,
            "lat": round(lat, 5),
            "lng": round(lng, 5),
            "surface": surface,
            "cage": cage,
            "size": [30, 16] if cage else [100, 64] if is_official else [40, 22],
            "access": "Vereinsgelände" if is_official else "Öffentlich",
            "amenities": {"flutlicht": is_official or cage, "umkleide": is_official, "toiletten": is_official},
            "desc": f"Öffentlicher Bolzplatz in {district}." if not is_official else f"Offizielle Sportanlage in {district}."
        })

    return converted


def get_all_pitches(include_live_photon: bool = True, verbose: bool = True) -> List[Dict[str, Any]]:
    """Combines curated official & unofficial databases with live geodata and deduplicates."""
    combined = list(OFFICIAL_VENUES_REGISTRY) + list(UNOFFICIAL_PITCHES_REGISTRY)

    if include_live_photon:
        try:
            live = collect_live_pitches(verbose=verbose)
            combined.extend(live)
        except Exception:
            pass

    # Deduplicate pitches by proximity (< 80m) or identical coordinates
    unique_pitches = []
    for p in combined:
        duplicate = False
        for u in unique_pitches:
            dist_m = haversine_km(p["lat"], p["lng"], u["lat"], u["lng"]) * 1000.0
            if dist_m < 80.0:
                duplicate = True
                break
        if not duplicate:
            unique_pitches.append(p)

    # Assign IDs, rating metrics, capacities and defaults
    final_pitches = []
    for i, p in enumerate(unique_pitches, 1):
        pid = f"p{i}"
        p_obj = dict(p)
        p_obj["id"] = pid
        p_obj["now"] = "frei"
        p_obj["maxPlayers"] = 16 if p_obj["size"][0] >= 80 else 10 if p_obj["size"][0] >= 35 else 8
        p_obj.setdefault("rating", 4.3 if p_obj["access"] != "Öffentlich" else 4.1)
        p_obj.setdefault("ratingCount", 22 if p_obj["access"] != "Öffentlich" else 16)
        p_obj.setdefault("club", None)
        p_obj.setdefault("occupations", [])
        final_pitches.append(p_obj)

    if verbose:
        official_count = sum(1 for p in final_pitches if p["access"] != "Öffentlich")
        unofficial_count = sum(1 for p in final_pitches if p["access"] == "Öffentlich")
        print(f"[Pitch Scraper] Total pitches compiled: {len(final_pitches)} (Official: {official_count}, Unofficial: {unofficial_count})")

    return final_pitches
