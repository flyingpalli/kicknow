def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Calculate great-circle distance between two GPS coordinates in kilometers."""
    r = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlam = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2.0) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlam / 2.0) ** 2
    return 2.0 * r * math.asin(math.sqrt(a))


def _http_get(url: str, extra_headers: Optional[Dict[str, str]] = None, timeout: int = 12) -> str:
    hdrs = dict(HTTP_HEADERS)
    if extra_headers:
        hdrs.update(extra_headers)
    req = urllib.request.Request(url, headers=hdrs)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read().decode("utf-8", errors="ignore")


def _polygon_centroid(coords: Any) -> Optional[Tuple[float, float]]:
    """Compute (lat, lng) centroid for a GeoJSON Polygon or MultiPolygon."""
    try:
        ring = coords
        while isinstance(ring, list) and ring and isinstance(ring[0], list) and isinstance(ring[0][0], list):
            ring = ring[0]
        if not ring:
            return None
        lngs = [pt[0] for pt in ring if isinstance(pt, (list, tuple)) and len(pt) >= 2]
        lats = [pt[1] for pt in ring if isinstance(pt, (list, tuple)) and len(pt) >= 2]
        if not lngs or not lats:
            return None
        return round(sum(lats) / len(lats), 6), round(sum(lngs) / len(lngs), 6)
    except Exception:
        return None


def parse_osm_elements(elements: List[Dict[str, Any]], city_name: str = "München") -> List[Dict[str, Any]]:
    """Parse raw Overpass API JSON elements into normalized pitch dictionaries."""
    results = []
    for el in elements:
        tags = el.get("tags", {})
        lat = el.get("lat") or el.get("center", {}).get("lat")
        lng = el.get("lon") or el.get("center", {}).get("lon")
        if not lat or not lng:
            continue

        name_raw = (tags.get("name") or "").strip()
        name_lower = name_raw.lower()
        surface_raw = tags.get("surface", "unbekannt").lower()
        surface = SURFACE_MAP.get(surface_raw, "Kunstrasen" if "kunstrasen" in name_lower else "Rasenplatz")
        lit = tags.get("lit") == "yes"

        is_sports_centre = tags.get("leisure") == "sports_centre" or bool(tags.get("operator")) or bool(tags.get("club"))
        has_facility_kw = any(k in name_lower for k in ("sportanlage", "bezirkssportanlage", "sportpark", "stadion", "kampfbahn", "sv ", "tsv ", "fc ", "sc ", "1. "))
        access_tag = tags.get("access")

        if access_tag in ("yes", "public", "permissive"):
            access = "Öffentlich"
        elif access_tag in ("private", "club", "members", "no") or is_sports_centre or has_facility_kw:
            access = "Vereinsgelände"
        else:
            access = "Öffentlich"

        cage = tags.get("fence") == "yes" or "cage" in name_lower or "käfig" in name_lower
        district = tags.get("addr:suburb") or tags.get("addr:district") or city_name
        street = tags.get("addr:street", "Sportplatz")
        hnr = tags.get("addr:housenumber", "")

        results.append({
            "id": f"osm_{el['id']}",
            "osm_id": el["id"],
            "name": name_raw or (f"Sportanlage {district}" if access == "Vereinsgelände" else f"Bolzplatz {district}"),
            "city": city_name,
            "district": district,
            "address": f"{street} {hnr}".strip() + f", {city_name}",
            "lat": float(lat),
            "lng": float(lng),
            "surface": surface,
            "cage": cage,
            "size": [105, 68] if access == "Vereinsgelände" else [40, 24],
            "maxPlayers": 22 if access == "Vereinsgelände" else 12,
            "lit": lit,
            "access": access,
            "club": tags.get("operator") if access == "Vereinsgelände" else None,
            "amenities": {
                "flutlicht": lit or access == "Vereinsgelände",
                "umkleide": access == "Vereinsgelände",
                "toiletten": access == "Vereinsgelände" or tags.get("toilets") == "yes"
            },
            "desc": tags.get("description") or f"{'Vereinsplatz' if access == 'Vereinsgelände' else 'Öffentlicher Bolzplatz'} in {city_name}.",
            "rating": 4.4 if access == "Vereinsgelände" else 4.2,
            "ratingCount": 18,
            "occupations": []
        })
    return results


