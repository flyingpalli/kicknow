def fetch_osm_pitches(bbox: tuple, city_name: str = "München", live: bool = True) -> List[Dict[str, Any]]:
    """Harvests soccer pitches for a city using municipal geoportals, Overpass API, and curated registries."""
    min_lat, min_lng, max_lat, max_lng = bbox

    city_key = None
    for k, cfg in CITIES.items():
        if cfg["name"] == city_name or cfg["bbox"] == bbox:
            city_key = k
            break

    base_pitches = [dict(p) for p in CURATED_MULTI_CITY_PITCHES.get(city_key, [])] if city_key else []
    if not live:
        return base_pitches

    live_candidates: List[Dict[str, Any]] = []
    if city_key:
        live_candidates.extend(fetch_municipal_pitches(city_key))

    # Overpass API query with proper User-Agent header and facility-level ways
    query = f"""
    [out:json][timeout:18];
    (
      way["leisure"="sports_centre"]["sport"="soccer"]({min_lat},{min_lng},{max_lat},{max_lng});
      way["leisure"="pitch"]["sport"="soccer"]["name"]({min_lat},{min_lng},{max_lat},{max_lng});
    );
    out center tags;
    """
    try:
        body = urllib.parse.urlencode({"data": query}).encode("utf-8")
        req = urllib.request.Request(OVERPASS_URL, data=body, headers=HTTP_HEADERS)
        with urllib.request.urlopen(req, timeout=15) as resp:
            elements = json.loads(resp.read().decode("utf-8", errors="ignore")).get("elements", [])
            live_candidates.extend(parse_osm_elements(elements, city_name=city_name))
    except Exception:
        pass

    if not base_pitches:
        return live_candidates

    # Merge live candidates into base_pitches with 150m/80m spatial deduplication (capped at 60 per city)
    merged = list(base_pitches)
    for cand in live_candidates:
        if len(merged) >= 60:
            break
        min_d = 0.15 if cand.get("access") != "Öffentlich" else 0.08
        if any(haversine_km(cand["lat"], cand["lng"], ex["lat"], ex["lng"]) < min_d for ex in merged):
            continue
        cand_copy = dict(cand)
        cand_copy.setdefault("id", f"{city_key or 'osm'}_{len(merged) + 1}")
        cand_copy.setdefault("rating", 4.3)
        cand_copy.setdefault("ratingCount", 18)
        cand_copy.setdefault("occupations", [])
        merged.append(cand_copy)

    return merged


def get_multi_city_pitches(city_keys: Optional[List[str]] = None, live_osm: bool = False) -> List[Dict[str, Any]]:
    """Return pitches across all configured non-Munich cities (or specified city keys)."""
    keys = city_keys or ["nuremberg", "berlin", "hamburg", "cologne", "frankfurt"]
    all_pitches = []
    for k in keys:
        if k not in CITIES:
            continue
        cfg = CITIES[k]
        if live_osm:
            pitches = fetch_osm_pitches(cfg["bbox"], city_name=cfg["name"], live=True)
        else:
            pitches = [dict(p) for p in CURATED_MULTI_CITY_PITCHES.get(k, [])]
        all_pitches.extend(pitches)
    return all_pitches
