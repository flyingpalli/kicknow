def _http_get(url: str, timeout: int = 12) -> str:
    req = urllib.request.Request(url, headers=HTTP_HEADERS)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read().decode("utf-8", errors="ignore")


def sanitize_match_record(record: Dict[str, Any]) -> Dict[str, Any]:
    """Ensure GDPR compliance by stripping any personal player or contact fields."""
    allowed_keys = {
        "date", "time", "minute_start", "home", "away", "league",
        "venue_name", "venue_addr", "surface", "reported_by_club", "association", "city", "source"
    }
    clean = {k: v for k, v in record.items() if k in allowed_keys}
    clean.setdefault("source", "fussball.de")
    return clean


def parse_fussball_de_html(
    html: str,
    default_city: str = "Berlin",
    association: str = "BFV_BERLIN",
    reported_by_club: str = ""
) -> List[Dict[str, Any]]:
    """Parse Fussball.de club fixture HTML (both live 3-row layout and compact table rows) into sanitized dicts."""
    matches: List[Dict[str, Any]] = []

    # 1. Live Fussball.de 3-row layout (tr.row-headline + tr.row-competition + teams tr)
    if "row-headline" in html:
        blocks = re.split(r'<tr class="row-headline[^"]*">', html)[1:]
        for block in blocks:
            hl_m = re.search(r"<td[^>]*>(.*?)</td>", block, re.DOTALL)
            if not hl_m:
                continue
            hl_text = html_lib.unescape(re.sub(r"<[^>]+>", "", hl_m.group(1))).strip()
            dt_m = re.search(r"(\d{2})\.(\d{2})\.(\d{4})\s*-\s*(\d{1,2}):(\d{2})", hl_text)
            if not dt_m:
                continue
            day, month, year, hour_s, min_s = dt_m.groups()
            date_iso = f"{year}-{month}-{day}"
            h, m = int(hour_s), int(min_s)
            time_str = f"{h:02d}:{m:02d}"
            min_start = h * 60 + m

            hl_parts = [p.strip() for p in hl_text.split("|")]
            league = hl_parts[-1] if len(hl_parts) >= 2 else "Kreisliga"

            teams = [
                html_lib.unescape(t).strip()
                for t in re.findall(r'<div class="club-name">\s*([^<]+?)\s*</div>', block)
            ]
            if len(teams) < 2:
                continue

            raw = {
                "date": date_iso,
                "time": time_str,
                "minute_start": min_start,
                "home": teams[0],
                "away": teams[1],
                "league": league,
                "venue_name": f"Sportanlage {teams[0]}",
                "venue_addr": default_city,
                "reported_by_club": reported_by_club or teams[0],
                "association": association,
                "city": default_city,
                "source": "fussball.de"
            }
            matches.append(sanitize_match_record(raw))
        if matches:
            return matches

    # 2. Compact / single-row fixture layout (tr.row-competition, tr.club-match-row, div.match-row)
    row_pattern = re.compile(
        r'<(?:tr|div)[^>]*class="[^"]*(?:row-competition|club-match-row|match-row)[^"]*"([^>]*)>(.*?)</(?:tr|div)>',
        re.DOTALL
    )
    for attrs, inner in row_pattern.findall(html):
        d_m = re.search(r'data-date="([^"]+)"', attrs)
        t_m = re.search(r'data-time="([^"]+)"', attrs)
        date_text = d_m.group(1) if d_m else ""
        time_text = t_m.group(1) if t_m else "14:00"

        teams = [
            html_lib.unescape(re.sub(r"<[^>]+>", "", t)).strip()
            for t in re.findall(r'<[^>]*class="[^"]*(?:club-name|team-name)[^"]*"[^>]*>(.*?)</[^>]+>', inner, re.DOTALL)
        ]
        if len(teams) < 2:
            continue

        league_m = re.search(r'<[^>]*class="[^"]*(?:competition-name|league-name)[^"]*"[^>]*>(.*?)</[^>]+>', inner, re.DOTALL)
        venue_m = re.search(r'<[^>]*class="[^"]*(?:venue-name|location)[^"]*"[^>]*>(.*?)</[^>]+>', inner, re.DOTALL)
        addr_m = re.search(r'<[^>]*class="[^"]*(?:venue-address|address)[^"]*"[^>]*>(.*?)</[^>]+>', inner, re.DOTALL)

        m_date = re.search(r"(\d{4}-\d{2}-\d{2})", date_text)
        date_iso = m_date.group(1) if m_date else "2026-10-18"

        m_time = re.search(r"(\d{1,2}):(\d{2})", time_text)
        if m_time:
            h, m = int(m_time.group(1)), int(m_time.group(2))
            time_str = f"{h:02d}:{m:02d}"
            min_start = h * 60 + m
        else:
            time_str = "14:00"
            min_start = 840

        raw = {
            "date": date_iso,
            "time": time_str,
            "minute_start": min_start,
            "home": teams[0],
            "away": teams[1],
            "league": html_lib.unescape(re.sub(r"<[^>]+>", "", league_m.group(1))).strip() if league_m else "Kreisliga",
            "venue_name": html_lib.unescape(re.sub(r"<[^>]+>", "", venue_m.group(1))).strip() if venue_m else "Sportanlage",
            "venue_addr": html_lib.unescape(re.sub(r"<[^>]+>", "", addr_m.group(1))).strip() if addr_m else default_city,
            "reported_by_club": reported_by_club or teams[0],
            "association": association,
            "city": default_city,
            "source": "fussball.de"
        }
        matches.append(sanitize_match_record(raw))

    return matches


def fetch_fussball_de_match_venue(match_url: str) -> Tuple[str, str, str]:
    """Extract (surface, venue_name, venue_addr) from a Fussball.de match detail page."""
    try:
        page = _http_get(match_url, timeout=10)
        for m in re.finditer(r'<a\s+[^>]*class="location"[^>]*>\s*([^<]+)', page):
            loc_txt = html_lib.unescape(m.group(1)).strip()
            parts = [p.strip() for p in loc_txt.split(",") if p.strip()]
            if len(parts) >= 3:
                s_low = parts[0].lower()
                surface = (
                    "Kunstrasen" if "kunstrasen" in s_low
                    else "Hartplatz" if ("hartplatz" in s_low or "tenne" in s_low or "asche" in s_low)
                    else "Asphalt" if "asphalt" in s_low
                    else "Rasenplatz"
                )
                return surface, parts[1], ", ".join(parts[2:])
    except Exception:
        pass
    return "Kunstrasen", "Sportanlage", ""


def discover_city_clubs(city_key: str, live: bool = False, max_pages: int = 1) -> List[Dict[str, Any]]:
    """Discover football clubs for a city via BFV, HFV Hamburg directory, and Fussball.de JSON search."""
    if not live:
        return [dict(c) for c in CURATED_REGIONAL_CLUBS.get(city_key, [])]

    city_cfg = CITIES.get(city_key, CITIES["berlin"])
    city_name = city_cfg["name"]
    assoc = city_cfg["association"]
    prefixes = tuple(city_cfg.get("plz_prefixes", ()))

    if city_key == "nuremberg":
        found = bfv_search_clubs("Nürnberg", city_key="nuremberg")
        if found:
            return found
        return [dict(c) for c in CURATED_REGIONAL_CLUBS.get(city_key, [])]

    clubs: List[Dict[str, Any]] = []
    seen = set()
    query_str = "Frankfurt am Main" if city_key == "frankfurt" else city_name
    for page in range(max_pages):
        url = FUSSBALL_DE_CLUB_SEARCH_URL.format(offset=page * 100, query=urllib.parse.quote(query_str))
        try:
            data = json.loads(_http_get(url, timeout=12))
            raw_html = data.get("html") or ""
            pattern = re.compile(
                r'href="(https://www\.fussball\.de/verein/[^"]+/id/([0-9A-Z]{32}))".*?'
                r'<p class="name">([^<]+).*?<p class="sub">([^<]+)',
                re.DOTALL
            )
            for href, cid, name, sub in pattern.findall(raw_html):
                if cid in seen:
                    continue
                sub_clean = html_lib.unescape(sub).replace("\xa0", " ").strip()
                name_clean = html_lib.unescape(name).strip()
                if prefixes and not any(sub_clean.startswith(p) for p in prefixes):
                    continue
                seen.add(cid)
                clubs.append({
                    "id": cid,
                    "name": name_clean,
                    "city": sub_clean,
                    "region_city": city_name,
                    "association": assoc,
                    "address": sub_clean,
                    "url": href
                })
            if data.get("final"):
                break
        except Exception:
            break

    # Supplement Hamburg with official HFV directory (hfv.de/vereine/)
    if city_key == "hamburg":
        hfv_url = city_cfg.get("municipal_endpoints", {}).get("hfv_clubs_url")
        if hfv_url:
            try:
                hfv_html = _http_get(hfv_url, timeout=12)
                existing_names = {c["name"].lower() for c in clubs}
                for href, name in re.findall(r'<a[^>]+href="(https://www\.hfv\.de/vereine/[^"/]+/)"[^>]*>\s*([^<]+?)\s*</a>', hfv_html):
                    n_clean = html_lib.unescape(name).strip()
                    if n_clean and n_clean.lower() not in existing_names:
                        slug = href.rstrip("/").split("/")[-1]
                        clubs.append({
                            "id": f"hfv_{slug[:28]}",
                            "name": n_clean,
                            "city": "Hamburg",
                            "region_city": "Hamburg",
                            "association": "HFV",
                            "address": "Hamburg",
                            "url": href
                        })
            except Exception:
                pass

    if not clubs:
        return [dict(c) for c in CURATED_REGIONAL_CLUBS.get(city_key, [])]
    return clubs


def scrape_city_matches(
    city_key: str,
    club_urls: Optional[List[str]] = None,
    live: bool = False,
    max_clubs: int = 6
) -> List[Dict[str, Any]]:
    """Fetch scheduled matches for a given city key, respecting GDPR and fallback fixtures."""
    city_cfg = CITIES.get(city_key, CITIES["munich"])
    city_name = city_cfg["name"]
    assoc = city_cfg["association"]
    results: List[Dict[str, Any]] = []

    if live:
        if club_urls:
            for url in club_urls:
                try:
                    raw = _http_get(url, timeout=12)
                    results.extend(parse_fussball_de_html(raw, default_city=city_name, association=assoc))
                except Exception:
                    continue
        elif city_key == "nuremberg":
            try:
                nbg_data = scrape_nuremberg_bfv_data(max_clubs=max_clubs, verbose=False)
                results.extend( sanitize_match_record(dict(m)) for m in nbg_data.get("matches", []) )
            except Exception:
                pass
        else:
            clubs = discover_city_clubs(city_key, live=True, max_pages=1)
            venue_cache: Dict[str, Tuple[str, str, str]] = {}
            for club in clubs[:max_clubs]:
                cid = club["id"]
                if cid.startswith("hfv_"):
                    continue
                mp_url = FUSSBALL_DE_CLUB_MATCHPLAN_URL.format(club_id=cid)
                try:
                    mp_data = json.loads(_http_get(mp_url, timeout=10))
                    mp_html = mp_data.get("html") or ""
                    parsed = parse_fussball_de_html(
                        mp_html,
                        default_city=city_name,
                        association=assoc,
                        reported_by_club=club["name"]
                    )
                    spiel_m = re.search(r'href="(https://www\.fussball\.de/spiel/[^"]+)"', mp_html)
                    if cid not in venue_cache and spiel_m:
                        surf, v_name, v_addr = fetch_fussball_de_match_venue(spiel_m.group(1))
                        if v_addr:
                            venue_cache[cid] = (surf, v_name, v_addr)
                    if cid in venue_cache:
                        surf, v_name, v_addr = venue_cache[cid]
                        for pm in parsed:
                            pm["surface"] = surf
                            pm["venue_name"] = v_name
                            pm["venue_addr"] = v_addr
                    results.extend(parsed[:5])
                except Exception:
                    continue

    # Always merge curated regional matches so key city venues have verified occupations
    curated = [sanitize_match_record(dict(m)) for m in CURATED_REGIONAL_MATCHES.get(city_key, [])]
    seen_keys = {(m["date"], m["time"], m["home"]) for m in results}
    for cm in curated:
        if (cm["date"], cm["time"], cm["home"]) not in seen_keys:
            results.append(cm)

    return results


def scrape_all_cities_matches(city_keys: Optional[List[str]] = None, live: bool = False) -> List[Dict[str, Any]]:
    """Aggregate matches across all target non-Munich cities."""
    keys = city_keys or ["nuremberg", "berlin", "hamburg", "cologne", "frankfurt"]
    all_matches: List[Dict[str, Any]] = []
    for k in keys:
        all_matches.extend(scrape_city_matches(k, live=live))
    return all_matches


def scrape_all_cities_clubs(city_keys: Optional[List[str]] = None, live: bool = False) -> List[Dict[str, Any]]:
    """Aggregate clubs across all target non-Munich cities."""
    keys = city_keys or ["nuremberg", "berlin", "hamburg", "cologne", "frankfurt"]
    all_clubs: List[Dict[str, Any]] = []
    for k in keys:
        all_clubs.extend(discover_city_clubs(k, live=live))
    return all_clubs
